const validInstructions = `---
description: Reviews pull requests.
---

You review pull requests carefully.
`

func writeAgent(t *testing.T, name, instructions string) string {
	t.Helper()
	root := filepath.Join(t.TempDir(), name)
	if err := os.Mkdir(root, 0o755); err != nil {
		t.Fatal(err)
	}
	if instructions != "" {
		if err := os.WriteFile(filepath.Join(root, "instructions.md"), []byte(instructions), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// TestFiveMinuteJourney is the literal first journey: an authored directory
// applies into both harnesses' native always-on files, defaulting the
// workspace to the agent directory and honoring an explicit one.
func TestFiveMinuteJourney(t *testing.T) {
	agent := writeAgent(t, "my-agent", validInstructions)

	var stdout, stderr bytes.Buffer
	if code := run([]string{"apply", agent, "--harness", "claude"}, nil, &stdout, &stderr); code != 0 {
		t.Fatalf("apply exit %d\nstdout: %s\nstderr: %s", code, stdout.String(), stderr.String())
	}
	claudeMD, err := os.ReadFile(filepath.Join(agent, "CLAUDE.md"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(claudeMD), "<!-- Generated by tenon apply") {
		t.Fatalf("generated file must be visibly tool-owned: %q", claudeMD)
	}
	if !strings.Contains(string(claudeMD), "You review pull requests carefully.") {
		t.Fatalf("generated file must carry the body: %q", claudeMD)
	}
	if strings.Contains(string(claudeMD), "description:") {
		t.Fatalf("generated file must not carry frontmatter: %q", claudeMD)
	}
	if _, err := os.Stat(filepath.Join(agent, ".mcp.json")); err != nil {
		t.Fatal("claude must receive the generated managed MCP server:", err)
	}

	workspace := t.TempDir()
	stdout.Reset()
	stderr.Reset()
	if code := run([]string{"apply", agent, "--harness", "codex", "--workspace", workspace}, nil, &stdout, &stderr); code != 0 {
		t.Fatalf("codex apply exit %d\nstderr: %s", code, stderr.String())
	}
	if _, err := os.Stat(filepath.Join(workspace, "AGENTS.md")); err != nil {
		t.Fatal("agent source must apply outside its own directory:", err)
	}
	if _, err := os.Stat(filepath.Join(workspace, ".codex", "config.toml")); err != nil {
		t.Fatal("codex must receive the generated managed MCP server:", err)
	}
	if _, err := os.Stat(filepath.Join(agent, "AGENTS.md")); !os.IsNotExist(err) {
		t.Fatal("codex output must land in the selected workspace only")
	}
}

// TestCheckReportsApplyFailuresWithoutMutating proves check/apply
// parity: identical stable identifiers, and no workspace mutation from
// either command on a failing project.
func TestCheckReportsApplyFailuresWithoutMutating(t *testing.T) {
	agent := writeAgent(t, "my-agent", validInstructions)
	// A schedule with a malformed cron fails check and apply identically.
	if err := os.Mkdir(filepath.Join(agent, "schedules"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(agent, "schedules", "bad.md"),
		[]byte("---\ncron: not a cron\n---\n\nDo the thing.\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	var checkOut, applyOut, stderr bytes.Buffer
	checkCode := run([]string{"check", agent, "--harness", "claude", "--format", "jsonl"}, nil, &checkOut, &stderr)
	applyCode := run([]string{"apply", agent, "--harness", "claude", "--format", "jsonl"}, nil, &applyOut, &stderr)
	if checkCode == 0 || applyCode == 0 {
		t.Fatalf("both must fail: check=%d apply=%d", checkCode, applyCode)
	}
	if checkDiagnostics(t, checkOut.String()) != checkDiagnostics(t, applyOut.String()) {
		t.Fatalf("check and apply must report identical diagnostics:\n%s\n%s",
			checkOut.String(), applyOut.String())
	}
	if _, err := os.Stat(filepath.Join(agent, "CLAUDE.md")); !os.IsNotExist(err) {
		t.Fatal("a failing apply must not mutate the workspace")
	}
	if _, err := os.Stat(filepath.Join(agent, ".tenon")); !os.IsNotExist(err) {
		t.Fatal("a failing apply must not write state")
	}
}

// TestJSONLDiagnosticsAreParseable proves the machine-readable contract: one
// JSON object per line carrying the stable identifier, authored path, and
// rule.
func TestJSONLDiagnosticsAreParseable(t *testing.T) {
	agent := writeAgent(t, "my-agent", "no frontmatter\n")

	var stdout, stderr bytes.Buffer
	if code := run([]string{"check", agent, "--harness", "codex", "--format", "jsonl"}, nil, &stdout, &stderr); code == 0 {
		t.Fatal("expected validation failure")
	}
	lines := strings.Split(strings.TrimSpace(checkDiagnostics(t, stdout.String())), "\n")
	if len(lines) == 0 || lines[0] == "" {
		t.Fatal("expected at least one JSONL diagnostic")
	}
	sawMissingFrontmatter := false
	for _, line := range lines {
		var d struct {
			ID       string `json:"id"`
			Severity string `json:"severity"`
			Path     string `json:"path"`
			Rule     string `json:"rule"`
		}
		if err := json.Unmarshal([]byte(line), &d); err != nil {
			t.Fatalf("line %q is not one JSON diagnostic: %v", line, err)
		}
		if d.ID == "" || d.Severity == "" || d.Path == "" || d.Rule == "" {
			t.Fatalf("diagnostic must carry id, severity, path, and rule: %q", line)
		}
		if d.ID == "instructions.frontmatter.missing" && d.Path == "instructions.md" {
			sawMissingFrontmatter = true
		}
	}
	if !sawMissingFrontmatter {
		t.Fatalf("expected instructions.frontmatter.missing at instructions.md, got %v", lines)
	}
}

// TestEmitFilesListsFilesAndMatchesRollup proves the literal deliverable of
// issue #1: --emit files lists every authored file feeding the fingerprint
// with its own hash and executable bit, sorted by path, followed by the same
// rolled-up fingerprint check reports for the identical project.
func TestEmitFilesListsFilesAndMatchesRollup(t *testing.T) {
	// The absence of --harness is the subject here, so the developer's own
	// TENON_HARNESS must not supply one: with it set, these runs would take
	// the harness path and the assertions below would prove nothing.
	t.Setenv("TENON_HARNESS", "")
	agent := writeAgent(t, "my-agent", validInstructions)
	writeFile(t, agent, "harnesses/claude/.claude/hooks/pre.sh", []byte("#!/bin/sh\n"), 0o755)
	writeFile(t, agent, "harnesses/claude/.claude/settings.json", []byte(`{"a":1}`), 0o644)

	var checkOut, stderr bytes.Buffer
	if code := run([]string{"check", agent, "--harness", "claude"}, nil, &checkOut, &stderr); code != 0 {
		t.Fatalf("check exit %d: %s", code, stderr.String())
	}
	i := strings.Index(checkOut.String(), "fingerprint ")
	if i < 0 {
		t.Fatalf("check output missing fingerprint: %s", checkOut.String())
	}
	wantFingerprint := strings.TrimSuffix(checkOut.String()[i+len("fingerprint "):], ")\n")

	var stdout bytes.Buffer
	stderr.Reset()
	if code := run([]string{"check", agent, "--emit", "files"}, nil, &stdout, &stderr); code != 0 {
		t.Fatalf("check --emit files exit %d: %s", code, stderr.String())
	}
	lines := strings.Split(strings.TrimRight(stdout.String(), "\n"), "\n")
	if len(lines) < 4 {
		t.Fatalf("expected at least 3 file lines plus the summary, got %v", lines)
	}

	var paths []string
	byPath := make(map[string][2]string) // path -> [hash, mode]
	for _, line := range lines[:len(lines)-1] {
		fields := strings.Fields(line)
		if len(fields) != 3 {
			t.Fatalf("malformed file line %q", line)
		}
		paths = append(paths, fields[0])
		byPath[fields[0]] = [2]string{fields[1], fields[2]}
	}
	if !slices.IsSorted(paths) {
		t.Fatalf("file lines must be sorted by path: %v", paths)
	}
	if _, ok := byPath["instructions.md"]; !ok {
		t.Fatalf("instructions.md must be listed: %v", paths)
	}
	hook, ok := byPath["harnesses/claude/.claude/hooks/pre.sh"]
	if !ok || hook[1] != "x" {
		t.Fatalf("executable file must be listed with mode x: %v", byPath)
	}
	settings, ok := byPath["harnesses/claude/.claude/settings.json"]
	if !ok || settings[1] != "-" {
		t.Fatalf("non-executable file must be listed with mode -: %v", byPath)
	}
	if !strings.HasPrefix(hook[0], "sha256:") || !strings.HasPrefix(settings[0], "sha256:") {
		t.Fatalf("every file hash must carry the sha256: prefix: %v", byPath)
	}

	last := lines[len(lines)-1]
	wantLast := fmt.Sprintf("ok: agent my-agent (fingerprint %s)", wantFingerprint)
	if last != wantLast {
		t.Fatalf("last line = %q, want %q", last, wantLast)
	}
}

